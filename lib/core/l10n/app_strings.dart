  static String t(String key) {
    final table = lang == 'nl' ? _nl : _en;
    return table[key] ?? _en[key] ?? key;
  }

  static String fill(String key, Map<String, String> vars) {
    var value = t(key);
    vars.forEach((name, item) {
      value = value.replaceAll('{$name}', item);
    });
    return value;
  }

